        'meanBessSocFullLoss_kW', ...
        'peakBessSocFullLoss_kW', ...
        'meanBessSocEmptyLoss_kW', ...
        'peakBessSocEmptyLoss_kW', ...
        'meanDcdcConversionLoss_kW', ...
        'peakDcdcConversionLoss_kW', ...
        'meanDcdcPowerClipped_kW', ...
        'peakDcdcPowerClipped_kW', ...
